import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import type { OpenAPIV3_1 } from 'openapi-types'
import { buildWritableVariantMap, generateTypes } from 'openapi-zod-ts'
import { generateFixtures, type FixtureGenOptions } from '../plugins/fixtures.js'
import { generateHandlers } from '../plugins/handlers.js'
import { compileFiles, removeScratchDir, writeScratchFiles } from './scratch-files.js'

const OPTS: FixtureGenOptions = {
  seed: 42,
  maxArrayItems: 2,
  depthCap: 30,
  modelsImport: './models.js',
}

/** Fictional spec exercising every builder shape the generator distinguishes. */
const spec: OpenAPIV3_1.Document = {
  openapi: '3.1.0',
  info: { title: 'Fixtures', version: '1.0.0' },
  paths: {},
  components: {
    schemas: {
      PetStatus: { type: 'string', enum: ['available', 'sold'] },
      Pet: {
        type: 'object',
        required: ['id', 'name', 'status'],
        properties: {
          id: { type: 'string', format: 'uuid', readOnly: true },
          name: { type: 'string' },
          status: { $ref: '#/components/schemas/PetStatus' },
          tag: { type: 'string' },
          owner: { $ref: '#/components/schemas/Owner' },
          secret: { type: 'string', writeOnly: true },
        },
      },
      Owner: {
        type: 'object',
        required: ['email'],
        properties: {
          email: { type: 'string', format: 'email' },
          nickname: { type: 'string' },
        },
      },
      Event: {
        allOf: [
          {
            type: 'object',
            required: ['at'],
            properties: { at: { type: 'string', format: 'date-time' } },
          },
          { type: 'object', properties: { note: { type: 'string' } } },
        ],
      },
      TreeNode: {
        type: 'object',
        required: ['label'],
        properties: {
          label: { type: 'string' },
          children: { type: 'array', items: { $ref: '#/components/schemas/TreeNode' } },
        },
      },
      PetList: { type: 'array', items: { $ref: '#/components/schemas/Pet' } },
      Labels: { type: 'object', additionalProperties: { type: 'string' } },
      // A schema named like the Faker class must not clash with the faker import.
      Faker: { type: 'object', required: ['n'], properties: { n: { type: 'integer' } } },
      // A bare $ref alias (valid in 3.1, absent from the openapi-types SchemaObject union).
      PetAlias: { $ref: '#/components/schemas/Pet' } as unknown as OpenAPIV3_1.SchemaObject,
      // Three builder levels (Kennel -> Pet -> Owner) to exercise the FULL_DEPTH fallback.
      Kennel: {
        type: 'object',
        properties: { pets: { type: 'array', items: { $ref: '#/components/schemas/Pet' } } },
      },
      // Mutual cycle: Left <-> Right, guarded by cyclic() (an unguarded call would never end).
      Left: {
        type: 'object',
        required: ['right'],
        properties: { right: { $ref: '#/components/schemas/Right' } },
      },
      Right: {
        type: 'object',
        required: ['left'],
        properties: {
          left: { $ref: '#/components/schemas/Left' },
          owner: { $ref: '#/components/schemas/Owner' },
        },
      },
    },
  },
}

const { filename, content } = generateFixtures(spec, OPTS)

describe('generateFixtures: generated text', () => {
  it('writes fixtures.ts with the generated-file banner', () => {
    expect(filename).toBe('fixtures.ts')
    expect(content).toContain('auto-generated by @codewithagents/openapi-msw, do not edit')
  })

  it('imports model types from modelsImport and uses a private aliased Faker', () => {
    expect(content).toContain('from "./models.js"')
    expect(content).toMatch(/import type \{[^}]*\bPet\b[^}]*\} from "\.\/models\.js"/)
    expect(content).toContain("import { Faker as _Faker, base, en } from '@faker-js/faker'")
    expect(content).toContain('const faker = new _Faker({ locale: [en, base] })')
    expect(content).toContain('faker.seed([42, key, variant])')
  })

  it('honours a custom modelsImport', () => {
    const c = generateFixtures(spec, { ...OPTS, modelsImport: '../api/models.js' }).content
    expect(c).toContain('from "../api/models.js"')
  })

  it('emits a<Name> / an<Name> builders typed against the models', () => {
    expect(content).toContain('export function aPet(overrides?: Partial<Pet>, variant = 0): Pet {')
    expect(content).toContain('export function anOwner(overrides?: Partial<Owner>, variant = 0)')
    expect(content).toContain('export function anEvent(overrides?: Partial<Event>, variant = 0)')
    expect(content).toContain('aPet.full = (overrides?: Partial<Pet>, variant = 0): Pet =>')
  })

  it('emits value builders (no overrides) for non-object schemas', () => {
    expect(content).toContain('export function aPetStatus(variant = 0): PetStatus {')
    expect(content).toContain('export function aPetList(variant = 0): PetList {')
  })

  it('treats a $ref alias of an object schema as an object builder', () => {
    expect(content).toContain('export function aPetAlias(overrides?: Partial<PetAlias>')
  })

  it('delegates $refs outside a reference cycle to the referenced builder', () => {
    // required-only builder calls required-only builders; .full() calls .full()
    expect(content).toContain('"status": (aPetStatus(faker.number.int(0xffffffff)))')
    expect(content).toContain(
      '"owner": ((fullDepth < FULL_DEPTH ? anOwner.full : anOwner)(undefined, faker.number.int(0xffffffff)))'
    )
    expect(content).toContain('aPet(undefined, faker.number.int(0xffffffff))')
  })

  it('wraps $refs back into a reference cycle in the cyclic() recursion guard', () => {
    expect(content).toContain('cyclic(() => aRight(undefined, faker.number.int(0xffffffff)))')
    expect(content).toContain('cyclic(() => aLeft(undefined, faker.number.int(0xffffffff)))')
    expect(content).toContain(
      'cyclic(() => (fullDepth < FULL_DEPTH ? aTreeNode.full : aTreeNode)(undefined, faker.number.int(0xffffffff)))'
    )
    expect(content).not.toContain('cyclic(() => anOwner')
  })

  it('emits no imports for a spec without component schemas', () => {
    const empty = generateFixtures({ ...spec, components: {} }, OPTS).content
    expect(empty).not.toContain('import')
    expect(empty).toContain('export {}')
  })

  it('uses the configured seed', () => {
    expect(generateFixtures(spec, { ...OPTS, seed: 7 }).content).toContain('faker.seed([7, key')
  })
})

describe('handlers.ts output is unaffected by fixture-only options', () => {
  it('handlers still emit optional and writeOnly properties', () => {
    const withPath: OpenAPIV3_1.Document = {
      ...spec,
      paths: {
        '/pets': {
          get: {
            responses: {
              '200': {
                description: 'ok',
                content: { 'application/json': { schema: { $ref: '#/components/schemas/Pet' } } },
              },
            },
          },
        },
      },
    }
    const c = generateHandlers(withPath, { seed: 42, maxArrayItems: 2, depthCap: 30 }).content
    expect(c).toContain('"tag":')
    expect(c).toContain('"secret":')
  })
})

describe('generated fixtures typecheck against generated models', () => {
  it('compiles under strict with a consumer exercising overrides', () => {
    const models = generateTypes(spec, undefined, buildWritableVariantMap(spec)).content
    const consumer = [
      `import { aPet, anOwner, aPetStatus, aTreeNode, aLabels, aFaker } from './fixtures.js'`,
      `import type { Pet, PetStatus } from './models.js'`,
      `const p: Pet = aPet({ name: 'Rex', status: 'available' })`,
      `const f: Pet = aPet.full({ tag: 't' }, 2)`,
      `const s: PetStatus = aPetStatus(1)`,
      `void [p, f, s, anOwner().email, aTreeNode.full().label, aLabels(), aFaker().n]`,
      `// @ts-expect-error: overrides are type-checked against the model`,
      `aPet({ status: 'not-a-status' })`,
      `// @ts-expect-error: unknown keys are rejected`,
      `aPet({ nope: 1 })`,
    ].join('\n')
    const diagnostics = compileFiles({
      'models.ts': models,
      'fixtures.ts': content,
      'consumer.ts': consumer,
    })
    expect(diagnostics).toEqual([])
    // A full TypeScript program compile; under coverage instrumentation on CI
    // runners this exceeds vitest's 5s default.
  }, 30_000)
})

describe('generated fixtures at runtime', () => {
  type Builder = ((overrides?: object, variant?: number) => Record<string, unknown>) & {
    full: (overrides?: object, variant?: number) => Record<string, unknown>
  }
  let mod: Record<string, Builder>
  let dir: string

  beforeAll(async () => {
    dir = writeScratchFiles({ 'fixtures.ts': content })
    mod = (await import(pathToFileURL(join(dir, 'fixtures.ts')).href)) as Record<string, Builder>
  })
  afterAll(() => removeScratchDir(dir))

  it('is deterministic per call, independent of call order', () => {
    const first = mod['aPet']!()
    mod['anOwner']!()
    mod['aPet']!.full()
    expect(mod['aPet']!()).toEqual(first)
  })

  it('date fields are deterministic too (fixed faker reference date)', async () => {
    const first = mod['anEvent']!()
    await new Promise((r) => setTimeout(r, 5))
    expect(mod['anEvent']!()).toEqual(first)
    expect(content).toContain('faker.setDefaultRefDate("2025-01-01T00:00:00.000Z")')
  })

  it('a different variant gives a different value', () => {
    expect(mod['aPet']!({}, 1)['name']).not.toEqual(mod['aPet']!()['name'])
  })

  it('fills required properties only by default, omitting writeOnly', () => {
    expect(Object.keys(mod['aPet']!()).sort()).toEqual(['id', 'name', 'status'])
    expect(['available', 'sold']).toContain(mod['aPet']!()['status'])
  })

  it('.full() fills optional properties too (still omitting writeOnly)', () => {
    const full = mod['aPet']!.full()
    expect(Object.keys(full).sort()).toEqual(['id', 'name', 'owner', 'status', 'tag'])
    expect(Object.keys(full['owner'] as object).sort()).toEqual(['email', 'nickname'])
  })

  it('shallow-merges overrides', () => {
    const owner = { email: 'x@example.test' }
    const pet = mod['aPet']!({ name: 'Rex', owner })
    expect(pet['name']).toBe('Rex')
    expect(pet['owner']).toBe(owner)
    expect(pet['id']).toBe(mod['aPet']!()['id'])
  })

  it('terminates self-references after one nested level', () => {
    const tree = mod['aTreeNode']!.full()
    const children = tree['children'] as Record<string, unknown>[]
    expect(children).toHaveLength(2)
    expect(children[0]!['children']).toEqual([null, null])
    // the guard resets once the top-level call returns
    expect(mod['aTreeNode']!.full()).toEqual(tree)
  })

  it('terminates mutual reference cycles', () => {
    const left = mod['aLeft']!()
    expect(left['right']).toEqual({ left: null })
    expect(Object.keys(mod['aRight']!.full()).sort()).toEqual(['left', 'owner'])
  })

  it('a delegated nested value has the nested builder shape and stays deterministic', () => {
    const alias = mod['aPetAlias']!({}, 3)
    expect(Object.keys(alias).sort()).toEqual(['id', 'name', 'status'])
    expect(mod['aPetAlias']!({}, 3)).toEqual(alias)
  })

  it('.full() fills two builder levels, deeper nested builders are required-only', () => {
    const pets = mod['aKennel']!.full()['pets'] as Record<string, unknown>[]
    expect(Object.keys(pets[0]!).sort()).toEqual(['id', 'name', 'owner', 'status', 'tag'])
    expect(Object.keys(pets[0]!['owner'] as object)).toEqual(['email'])
  })

  it('array items built by a nested builder are distinct (siblings get distinct variants)', () => {
    const list = (mod['aPetList'] as unknown as (variant?: number) => { id: string }[])()
    expect(list).toHaveLength(2)
    expect(list[0]!.id).not.toBe(list[1]!.id)
  })
})

